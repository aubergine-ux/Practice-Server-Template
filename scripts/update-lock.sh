#!/usr/bin/env bash
# Resolves manifest.txt into pinned downloads:
#   versions.lock        <dest> <algo:hash> <url>   (read by setup.sh / setup.ps1)
#   docker/versions.env  same pins for the itzg/minecraft-server image
# Requires: curl, jq
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MANIFEST="$ROOT/manifest.txt"
LOCK="$ROOT/versions.lock"
ENV_FILE="$ROOT/docker/versions.env"
UA="minecraft-duels-template/update-lock (github.com)"

for bin in curl jq; do
  command -v "$bin" >/dev/null || { echo "error: '$bin' is required" >&2; exit 1; }
done

api() { curl -fsSL -A "$UA" "$@"; }

mc_version=""
lock_lines=()
modrinth_pins=()

while read -r kind name version _; do
  case "$kind" in
    ""|\#*) continue ;;
    paper)
      mc_version="$name"
      build="${version:-latest}"
      json=$(api "https://fill.papermc.io/v3/projects/paper/versions/$mc_version/builds/$build")
      if [[ -z "$version" && "$(jq -r .channel <<<"$json")" != "STABLE" ]]; then
        echo "warning: latest Paper $mc_version build is not STABLE" >&2
      fi
      paper_build=$(jq -r .id <<<"$json")
      url=$(jq -r '.downloads["server:default"].url' <<<"$json")
      sha=$(jq -r '.downloads["server:default"].checksums.sha256' <<<"$json")
      lock_lines+=("server.jar	sha256:$sha	$url")
      echo "paper $mc_version build $paper_build"
      ;;
    modrinth)
      [[ -n "$mc_version" ]] || { echo "error: 'paper' line must come before plugins" >&2; exit 1; }
      json=$(api -G "https://api.modrinth.com/v2/project/$name/version" \
        --data-urlencode 'loaders=["paper","bukkit","spigot"]' \
        --data-urlencode "game_versions=[\"$mc_version\"]")
      if [[ -n "$version" ]]; then
        pick=$(jq --arg v "$version" '[.[] | select(.version_number == $v)][0]' <<<"$json")
      else
        pick=$(jq '[.[] | select(.version_type == "release")][0]' <<<"$json")
      fi
      if [[ "$pick" == "null" ]]; then
        echo "error: no ${version:-release} version of '$name' for Paper $mc_version" >&2
        exit 1
      fi
      file=$(jq '([.files[] | select(.primary)] + .files)[0]' <<<"$pick")
      filename=$(jq -r .filename <<<"$file")
      url=$(jq -r .url <<<"$file")
      sha=$(jq -r .hashes.sha512 <<<"$file")
      vnum=$(jq -r .version_number <<<"$pick")
      lock_lines+=("plugins/$filename	sha512:$sha	$url")
      modrinth_pins+=("$name:$(jq -r .id <<<"$pick")")
      echo "$name $vnum"
      ;;
    *)
      echo "error: unknown manifest entry '$kind'" >&2
      exit 1
      ;;
  esac
done <"$MANIFEST"

{
  echo "# Generated by scripts/update-lock.sh from manifest.txt - do not edit by hand."
  echo "# <destination under server/>	<algorithm:hash>	<url>"
  printf '%s\n' "${lock_lines[@]}"
} >"$LOCK"

{
  echo "# Generated by scripts/update-lock.sh from manifest.txt - do not edit by hand."
  echo "TYPE=PAPER"
  echo "VERSION=$mc_version"
  echo "PAPER_BUILD=$paper_build"
  echo "MODRINTH_PROJECTS=$(IFS=,; echo "${modrinth_pins[*]}")"
} >"$ENV_FILE"

echo "wrote versions.lock and docker/versions.env"
